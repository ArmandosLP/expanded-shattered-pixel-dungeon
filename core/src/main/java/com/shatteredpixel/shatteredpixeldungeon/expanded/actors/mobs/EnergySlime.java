package com.shatteredpixel.shatteredpixeldungeon.expanded.actors.mobs;

import com.shatteredpixel.shatteredpixeldungeon.Dungeon;
import com.shatteredpixel.shatteredpixeldungeon.actors.mobs.Slime;
import com.shatteredpixel.shatteredpixeldungeon.expanded.sprites.EnergySlimeSprite;
import com.shatteredpixel.shatteredpixeldungeon.items.EnergyCrystal;
import com.shatteredpixel.shatteredpixeldungeon.items.Item;
import com.watabou.utils.PathFinder;
import com.watabou.utils.Random;

public class EnergySlime extends Slime {
	
	{
		spriteClass = EnergySlimeSprite.class;
	}

	@Override
	public void rollToDropLoot() {
		super.rollToDropLoot();

		int ofs;
		do {
			ofs = PathFinder.NEIGHBOURS8[Random.Int(8)];
		} while (Dungeon.level.solid[pos + ofs] && !Dungeon.level.passable[pos + ofs]);

		Dungeon.level.drop( new EnergyCrystal(Random.Int(3) + 1), pos + ofs ).sprite.drop( pos );
	}


    @Override
    public float lootChance(){
        return 0f; // Do not drop weapons
    }

    @Override
    public Item createLoot() {
        return null;
    }

}
